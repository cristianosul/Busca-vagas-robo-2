
import json
import os
import sqlite3
from contextlib import contextmanager
from datetime import datetime, timezone
from pathlib import Path
from urllib.parse import parse_qsl, urlencode, urlsplit, urlunsplit

from app.models import CandidateEvidence, CandidateIn, SourceCreate
from app.scoring import score_candidate


DATABASE_URL = os.getenv("DATABASE_URL", "").strip()
DB_PATH = Path(os.getenv("DATABASE_PATH", "./data/staging.db"))

TRACKING_KEYS = {
    "fbclid", "gclid", "dclid", "msclkid", "ref", "referrer"
}


def utc_now() -> str:
    return datetime.now(timezone.utc).isoformat()


def normalize_job_url(value: str) -> str:
    """Remove fragmentos e parâmetros de rastreamento."""
    parts = urlsplit(str(value).strip())
    scheme = parts.scheme.lower()
    hostname = (parts.hostname or "").lower()

    if scheme not in {"http", "https"} or not hostname:
        raise ValueError("URL original sem hostname válido.")

    try:
        port = parts.port
    except ValueError as exc:
        raise ValueError("Porta inválida na URL original.") from exc

    if ":" in hostname:
        hostname = f"[{hostname}]"

    if port and not (
        (scheme == "https" and port == 443)
        or (scheme == "http" and port == 80)
    ):
        netloc = f"{hostname}:{port}"
    else:
        netloc = hostname

    path = parts.path or "/"
    if path != "/":
        path = path.rstrip("/")

    query_items = []

    for key, val in parse_qsl(parts.query, keep_blank_values=True):
        lowered = key.lower()

        if lowered.startswith("utm_") or lowered in TRACKING_KEYS:
            continue

        query_items.append((key, val))

    query = urlencode(sorted(query_items))

    return urlunsplit((scheme, netloc, path, query, ""))


def connect():
    """Conecta ao Neon ou ao SQLite local."""
    if DATABASE_URL:
        try:
            import psycopg
            from psycopg.rows import dict_row
        except ImportError as exc:
            raise RuntimeError(
                "Driver PostgreSQL ausente. Instale psycopg[binary]."
            ) from exc

        return psycopg.connect(
            DATABASE_URL,
            sslmode="require",
            connect_timeout=10,
            row_factory=dict_row,
        )

    DB_PATH.parent.mkdir(parents=True, exist_ok=True)

    conn = sqlite3.connect(DB_PATH, timeout=30)
    conn.row_factory = sqlite3.Row
    conn.execute("PRAGMA busy_timeout = 30000")
    conn.execute("PRAGMA foreign_keys = ON")

    return conn


@contextmanager
def db_session(immediate: bool = False):
    """Garante transação e fechamento da conexão."""
    conn = connect()

    try:
        if not DATABASE_URL and immediate:
            conn.execute("BEGIN IMMEDIATE")

        with conn:
            yield conn
    finally:
        conn.close()


def execute(conn, sql, params=()):
    """Compatibiliza parâmetros SQLite e PostgreSQL."""
    if DATABASE_URL:
        sql = sql.replace("?", "%s")

    return conn.execute(sql, params)


def _get_table_columns(conn, table_name: str) -> set[str]:
    """Obtém as colunas existentes em SQLite ou PostgreSQL."""
    if table_name not in {"candidates", "sources"}:
        raise ValueError("Tabela não permitida para inspeção.")

    if DATABASE_URL:
        rows = conn.execute(
            """
            SELECT column_name
            FROM information_schema.columns
            WHERE table_schema = current_schema()
              AND table_name = ?
            """,
            (table_name,),
        ).fetchall()

        return {row["column_name"] for row in rows}

    rows = conn.execute(
        f"PRAGMA table_info({table_name})"
    ).fetchall()

    return {row["name"] for row in rows}


def _ensure_column(
    conn,
    table_name: str,
    column_name: str,
    column_definition: str,
):
    """Adiciona uma coluna somente quando ela ainda não existe."""
    allowed_columns = {
        "candidates": {
            "normalized_url",
            "evidence_json",
        },
        "sources": {
            "official_site_url",
            "authorization_evidence_url",
        },
    }

    if column_name not in allowed_columns.get(table_name, set()):
        raise ValueError("Coluna não permitida para migração.")

    columns = _get_table_columns(conn, table_name)

    if column_name not in columns:
        conn.execute(
            f"ALTER TABLE {table_name} "
            f"ADD COLUMN {column_name} {column_definition}"
        )


def serialize_source(row):
    """Padroniza os dados da fonte entre SQLite e PostgreSQL."""
    if row is None:
        return None

    result = dict(row)
    result["enabled"] = bool(result["enabled"])

    return result


def init_db():
    """Cria e atualiza as tabelas sem apagar registros existentes."""
    with db_session() as conn:
        if DATABASE_URL:
            conn.execute("""
                CREATE TABLE IF NOT EXISTS candidates (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    title TEXT NOT NULL,
                    company TEXT NOT NULL,
                    location TEXT,
                    mode TEXT NOT NULL,
                    source_name TEXT NOT NULL,
                    source_url TEXT NOT NULL,
                    original_job_url TEXT NOT NULL,
                    normalized_url TEXT,
                    application_url TEXT,
                    score INTEGER NOT NULL,
                    status TEXT NOT NULL
                        CHECK(status IN ('approved', 'review', 'rejected')),
                    reasons_json TEXT NOT NULL,
                    payload_json TEXT NOT NULL,
                    evidence_json TEXT NOT NULL DEFAULT '{}',
                    created_at TEXT NOT NULL
                )
            """)

            conn.execute("""
                CREATE TABLE IF NOT EXISTS sources (
                    source_id TEXT PRIMARY KEY,
                    name TEXT NOT NULL,
                    source_type TEXT NOT NULL,
                    base_url TEXT NOT NULL,
                    official_site_url TEXT,
                    authorization_evidence_url TEXT,
                    "authorization" TEXT NOT NULL,
                    enabled BOOLEAN NOT NULL DEFAULT FALSE,
                    notes TEXT,
                    created_at TEXT NOT NULL,
                    updated_at TEXT NOT NULL
                )
            """)
        else:
            conn.execute("""
                CREATE TABLE IF NOT EXISTS candidates (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    title TEXT NOT NULL,
                    company TEXT NOT NULL,
                    location TEXT,
                    mode TEXT NOT NULL,
                    source_name TEXT NOT NULL,
                    source_url TEXT NOT NULL,
                    original_job_url TEXT NOT NULL,
                    normalized_url TEXT,
                    application_url TEXT,
                    score INTEGER NOT NULL,
                    status TEXT NOT NULL
                        CHECK(status IN ('approved', 'review', 'rejected')),
                    reasons_json TEXT NOT NULL,
                    payload_json TEXT NOT NULL,
                    evidence_json TEXT NOT NULL DEFAULT '{}',
                    created_at TEXT NOT NULL
                )
            """)

            conn.execute("""
                CREATE TABLE IF NOT EXISTS sources (
                    source_id TEXT PRIMARY KEY,
                    name TEXT NOT NULL,
                    source_type TEXT NOT NULL,
                    base_url TEXT NOT NULL,
                    official_site_url TEXT,
                    authorization_evidence_url TEXT,
                    "authorization" TEXT NOT NULL,
                    enabled INTEGER NOT NULL DEFAULT 0,
                    notes TEXT,
                    created_at TEXT NOT NULL,
                    updated_at TEXT NOT NULL
                )
            """)

        # Migração compatível com bancos antigos.
        _ensure_column(
            conn,
            "candidates",
            "normalized_url",
            "TEXT",
        )

        _ensure_column(
            conn,
            "candidates",
            "evidence_json",
            "TEXT NOT NULL DEFAULT '{}'",
        )

        _ensure_column(
            conn,
            "sources",
            "official_site_url",
            "TEXT",
        )

        _ensure_column(
            conn,
            "sources",
            "authorization_evidence_url",
            "TEXT",
        )

        rows = execute(
            conn,
            """
            SELECT id, original_job_url
            FROM candidates
            WHERE normalized_url IS NULL OR normalized_url = ''
            ORDER BY id
            """
        ).fetchall()

        for row in rows:
            normalized = normalize_job_url(row["original_job_url"])

            execute(
                conn,
                """
                UPDATE candidates
                SET normalized_url = ?
                WHERE id = ?
                """,
                (normalized, row["id"]),
            )

        duplicates = execute(
            conn,
            """
            SELECT normalized_url, COUNT(*) AS total
            FROM candidates
            WHERE normalized_url IS NOT NULL
              AND normalized_url != ''
            GROUP BY normalized_url
            HAVING COUNT(*) > 1
            LIMIT 5
            """
        ).fetchall()

        if duplicates:
            examples = ", ".join(
                f"{row['normalized_url']} ({row['total']} registros)"
                for row in duplicates
            )
            raise RuntimeError(
                "Migração interrompida: existem URLs normalizadas "
                "duplicadas em candidates. Nenhum registro foi apagado. "
                f"Exemplos: {examples}"
            )

        conn.execute("""
            CREATE UNIQUE INDEX IF NOT EXISTS
            ux_candidates_normalized_url
            ON candidates(normalized_url)
        """)

        conn.execute("""
            CREATE INDEX IF NOT EXISTS
            ix_sources_enabled
            ON sources(enabled)
        """)


def save_candidate(
    candidate: CandidateIn,
    evidence: CandidateEvidence | None = None,
):
    """Salva oportunidade, pontuação e evidências individuais."""
    evidence = evidence or CandidateEvidence()

    score, status, reasons = score_candidate(evidence)

    payload = candidate.model_dump(mode="json")
    evidence_payload = evidence.model_dump(mode="json")

    created_at = utc_now()

    original_url = str(candidate.original_job_url)
    normalized_url = normalize_job_url(original_url)

    with db_session(immediate=True) as conn:
        cur = execute(
            conn,
            """
            INSERT INTO candidates (
                title, company, location, mode, source_name, source_url,
                original_job_url, normalized_url, application_url, score,
                status, reasons_json, payload_json, evidence_json,
                created_at
            )
            VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
            ON CONFLICT(normalized_url) DO NOTHING
            RETURNING id
            """,
            (
                candidate.title,
                candidate.company,
                candidate.location,
                candidate.mode,
                candidate.source_name,
                str(candidate.source_url),
                original_url,
                normalized_url,
                str(candidate.application_url)
                if candidate.application_url else None,
                score,
                status,
                json.dumps(reasons, ensure_ascii=False),
                json.dumps(payload, ensure_ascii=False),
                json.dumps(evidence_payload, ensure_ascii=False),
                created_at,
            ),
        )

        inserted = cur.fetchone()

        if inserted:
            return {
                "id": inserted["id"],
                "status": status,
                "score": score,
                "reasons": reasons,
            }

        existing = execute(
            conn,
            """
            SELECT id, status, score
            FROM candidates
            WHERE normalized_url = ?
            """,
            (normalized_url,),
        ).fetchone()

        if existing:
            return {
                "id": existing["id"],
                "status": "duplicate",
                "existing_status": existing["status"],
                "score": existing["score"],
                "reasons": [
                    "URL original já cadastrada após normalização; "
                    "nenhum novo registro foi criado."
                ],
            }

        raise RuntimeError(
            "Não foi possível salvar ou localizar a oportunidade."
        )


def save_source(source: SourceCreate):
    """Armazena uma fonte sempre inicialmente desativada."""
    data = source.model_dump(mode="json")

    if data["enabled"]:
        raise ValueError(
            "Uma nova fonte deve ser cadastrada desativada. "
            "A ativação depende de um processo interno de verificação."
        )

    now = utc_now()

    with db_session(immediate=True) as conn:
        cur = execute(
            conn,
            """
            INSERT INTO sources (
                source_id,
                name,
                source_type,
                base_url,
                official_site_url,
                authorization_evidence_url,
                "authorization",
                enabled,
                notes,
                created_at,
                updated_at
            )
            VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
            ON CONFLICT(source_id) DO NOTHING
            RETURNING source_id
            """,
            (
                data["source_id"],
                data["name"],
                data["source_type"],
                str(data["base_url"]),
                str(data["official_site_url"])
                if data.get("official_site_url") else None,
                str(data["authorization_evidence_url"])
                if data.get("authorization_evidence_url") else None,
                data["authorization"],
                False,
                data.get("notes"),
                now,
                now,
            ),
        )

        inserted = cur.fetchone()

        if not inserted:
            raise ValueError(
                "Já existe uma fonte com esse identificador."
            )

    return get_source_record(data["source_id"])


def get_source_record(source_id: str):
    """Consulta uma fonte pelo identificador."""
    with db_session() as conn:
        row = execute(
            conn,
            """
            SELECT *
            FROM sources
            WHERE source_id = ?
            """,
            (source_id,),
        ).fetchone()

    if not row:
        return None

    return serialize_source(row)


def list_sources(enabled_only: bool = False, limit: int = 500):
    """Lista fontes cadastradas."""
    limit = max(1, min(int(limit), 500))

    with db_session() as conn:
        if enabled_only:
            rows = execute(
                conn,
                """
                SELECT *
                FROM sources
                WHERE enabled = ?
                ORDER BY name ASC
                LIMIT ?
                """,
                (True, limit),
            ).fetchall()
        else:
            rows = execute(
                conn,
                """
                SELECT *
                FROM sources
                ORDER BY name ASC
                LIMIT ?
                """,
                (limit,),
            ).fetchall()

    return [serialize_source(row) for row in rows]


def update_source_status(source_id: str, enabled: bool):
    """Permite desativar uma fonte, mas bloqueia ativação direta."""
    if enabled:
        raise ValueError(
            "A ativação direta de fontes está bloqueada. "
            "É necessária uma verificação interna da autorização."
        )

    with db_session(immediate=True) as conn:
        cur = execute(
            conn,
            """
            UPDATE sources
            SET enabled = ?, updated_at = ?
            WHERE source_id = ?
            RETURNING source_id
            """,
            (False, utc_now(), source_id),
        )

        updated = cur.fetchone()

    if not updated:
        return None

    return get_source_record(source_id)


def list_candidates(status: str | None = None, limit: int = 50):
    """Lista oportunidades incluindo os dados e evidências armazenados."""
    limit = max(1, min(int(limit), 500))

    with db_session() as conn:
        if status:
            rows = execute(
                conn,
                """
                SELECT *
                FROM candidates
                WHERE status = ?
                ORDER BY id DESC
                LIMIT ?
                """,
                (status, limit),
            ).fetchall()
        else:
            rows = execute(
                conn,
                """
                SELECT *
                FROM candidates
                ORDER BY id DESC
                LIMIT ?
                """,
                (limit,),
            ).fetchall()

    results = []

    for row in rows:
        payload = json.loads(row["payload_json"] or "{}")
        evidence = json.loads(row["evidence_json"] or "{}")

        results.append({
            "id": row["id"],
            "title": row["title"],
            "company": row["company"],
            "location": row["location"],
            "mode": row["mode"],
            "source_name": row["source_name"],
            "source_url": row["source_url"],
            "original_job_url": row["original_job_url"],
            "application_url": row["application_url"],
            "employment_type": payload.get("employment_type"),
            "advertiser_company": payload.get("advertiser_company"),
            "hiring_company": payload.get("hiring_company"),
            "intermediary_name": payload.get("intermediary_name"),
            "date_posted": payload.get("date_posted"),
            "valid_through": payload.get("valid_through"),
            "score": row["score"],
            "status": row["status"],
            "reasons": json.loads(row["reasons_json"]),
            "evidence": evidence,
            "created_at": row["created_at"],
        })

    return results
